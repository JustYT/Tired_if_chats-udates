// Keep the displayed budget aligned with summarizer.compression_limit.
export function compressionView(strength, kind = 'daily', groupBy = 'days') {
  const limit = strength === 100 ? 0 : Math.max(60, 600 - 6 * strength);
  const details = strength < 35
    ? ['Команда довольна запуском: обновление доступно всем пользователям, обратная связь положительная.', 'Обсудили новые лимиты; решение примут после проверки нагрузки.', 'Участники недовольны задержкой: срок перенесён, новой даты пока нет.']
    : strength < 70
      ? ['Обновление доступно всем, команда довольна результатом.', 'Решение по лимитам примут после проверки нагрузки.', 'Срок перенесён; участники недовольны задержкой.']
      : ['Команда довольна результатом.', 'Ответ появится после проверки нагрузки.', 'Участники недовольны задержкой.'];
  const topics = ['Релиз доступен всем', 'Лимиты: решение после проверки', 'Запуск перенесён, новой даты нет'];
  const colors = ['🟢', '🟡', '🔴'];
  const rows = topics.map((topic, i) => `   ${colors[i]} ${topic}${limit ? ' - ' + details[i] : ''}`);
  return {
    limit,
    description: limit ? `До ${limit} знаков на тему` : 'Только заголовки',
    preview: kind === 'weekly'
      ? groupBy === 'chats'
        ? '🌈 **++Внешний чат++**\n' + rows[0] + '\n' + rows[2] + '\n\n➡️ **++Групповой чат++**\n' + rows[1]
        : '**28.09.2026**\n🌈 **++Внешний чат++**\n' + rows[0] + '\n\n➡️ **++Групповой чат++**\n' + rows[1] + '\n\n**29.09.2026**\n🌈 **++Внешний чат++**\n' + rows[2]
      : '**01.10.2026**\n🌈 **++Внешний чат++**\n' + rows.join('\n'),
  };
}
